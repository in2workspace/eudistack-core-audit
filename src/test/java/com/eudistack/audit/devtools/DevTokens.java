package com.eudistack.audit.devtools;

import com.nimbusds.jose.JOSEException;
import com.nimbusds.jose.JWSAlgorithm;
import com.nimbusds.jose.JWSHeader;
import com.nimbusds.jose.crypto.ECDSASigner;
import com.nimbusds.jose.jwk.Curve;
import com.nimbusds.jose.jwk.ECKey;
import com.nimbusds.jose.jwk.JWKSet;
import com.nimbusds.jose.jwk.gen.ECKeyGenerator;
import com.nimbusds.jwt.JWTClaimsSet;
import com.nimbusds.jwt.SignedJWT;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.text.ParseException;
import java.time.Duration;
import java.time.Instant;
import java.util.Date;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.UUID;

/**
 * LOCAL DEVELOPMENT ONLY. Signs access tokens with the layout of the Verifier ({@code power},
 * {@code mandator}, {@code mandatee}, {@code tenant}, {@code credential_type}) so the compose stack can
 * be exercised by hand without the Verifier: {@code ./gradlew devTokens}.
 *
 * <p>Writes into the output directory (git-ignored):
 * <ul>
 *   <li>{@code dev-key.jwk} — private key, reused by later runs so the stack keeps trusting new tokens;</li>
 *   <li>{@code audit-local.env} — {@code AUDIT_SECURITY_JWKS} and {@code AUDIT_SECURITY_TRUSTED_ISSUERS},
 *       read by {@code compose.yaml};</li>
 *   <li>one {@code *.jwt} per profile, valid for 12 hours.</li>
 * </ul>
 */
public final class DevTokens {

    static final String ISSUER_TEMPLATE = "https://{tenant}.127.0.0.1.nip.io/verifier";
    private static final Duration VALIDITY = Duration.ofHours(12);

    private DevTokens() {
    }

    public static void main(String[] args) throws IOException, JOSEException, ParseException {
        Path out = Path.of(args.length > 0 ? args[0] : "dev-tools/local-tokens");
        Files.createDirectories(out);
        ECKey key = loadOrCreateKey(out.resolve("dev-key.jwk"));

        Files.writeString(out.resolve("audit-local.env"),
                "# Generated by ./gradlew devTokens. LOCAL ONLY.\n"
                        + "AUDIT_SECURITY_JWKS=" + new JWKSet(key.toPublicJWK()) + "\n"
                        + "AUDIT_SECURITY_TRUSTED_ISSUERS=" + ISSUER_TEMPLATE + "\n",
                StandardCharsets.UTF_8);

        Map<String, String> tokens = new LinkedHashMap<>();
        tokens.put("writer", sign(key, system("issuer-client", "platform", "VATES-EUDISTACK",
                power("organization", "EUDISTACK", "Audit", "Write"))));
        tokens.put("auditor-red-logistica", sign(key, person("auditor-red", "red-logistica", "VATES-B00000001",
                power("organization", "RED-LOGISTICA", "Audit", "Read"))));
        tokens.put("domain-auditor-red-logistica", sign(key, person("auditor-acme", "red-logistica", "VATES-A11111111",
                power("domain", "RED-LOGISTICA", "Audit", "Read"))));
        tokens.put("auditor-sandbox", sign(key, person("auditor-sandbox", "sandbox", "VATES-B00000002",
                power("organization", "SANDBOX", "Audit", "Read"))));
        tokens.put("system-reader-sandbox", sign(key, system("siem-sandbox", "sandbox", "VATES-B00000002",
                power("organization", "SANDBOX", "Audit", "Read"))));
        tokens.put("admin", sign(key, person("platform-admin", "platform", "VATES-EUDISTACK",
                power("organization", "EUDISTACK", "System", "Administration"))));
        for (Map.Entry<String, String> token : tokens.entrySet()) {
            Files.writeString(out.resolve(token.getKey() + ".jwt"), token.getValue(), StandardCharsets.UTF_8);
        }
        System.out.println("Local tokens written to " + out.toAbsolutePath() + " (valid " + VALIDITY.toHours() + " h): "
                + String.join(", ", tokens.keySet()));
    }

    private static ECKey loadOrCreateKey(Path file) throws IOException, JOSEException, ParseException {
        if (Files.exists(file)) {
            return ECKey.parse(Files.readString(file, StandardCharsets.UTF_8));
        }
        ECKey key = new ECKeyGenerator(Curve.P_256).keyID("local-dev-" + UUID.randomUUID()).generate();
        Files.writeString(file, key.toJSONString(), StandardCharsets.UTF_8);
        return key;
    }

    private static Map<String, Object> power(String type, String domain, String function, String action) {
        return Map.of("type", type, "domain", domain, "function", function, "action", List.of(action));
    }

    private static JWTClaimsSet.Builder person(String subject, String tenant, String organization,
                                               Map<String, Object> power) {
        return base(subject, tenant, organization, power)
                .claim("credential_type", "learcredential.employee.sd.1")
                .claim("scope", "openid learcredential")
                .claim("mandatee", Map.of("firstName", "Ana", "lastName", "Pérez", "email", subject + "@example.org"));
    }

    private static JWTClaimsSet.Builder system(String subject, String tenant, String organization,
                                               Map<String, Object> power) {
        return base(subject, tenant, organization, power)
                .claim("credential_type", "learcredential.machine.sd.1")
                .claim("scope", "machine learcredential");
    }

    private static JWTClaimsSet.Builder base(String subject, String tenant, String organization,
                                             Map<String, Object> power) {
        Instant now = Instant.now();
        return new JWTClaimsSet.Builder()
                .issuer(ISSUER_TEMPLATE.replace("{tenant}", tenant))
                .subject(subject)
                .jwtID(UUID.randomUUID().toString())
                .issueTime(Date.from(now))
                .expirationTime(Date.from(now.plus(VALIDITY)))
                .claim("tenant", tenant)
                .claim("mandator", Map.of("organizationIdentifier", organization))
                .claim("power", List.of(power));
    }

    private static String sign(ECKey key, JWTClaimsSet.Builder claims) throws JOSEException {
        SignedJWT jwt = new SignedJWT(new JWSHeader.Builder(JWSAlgorithm.ES256).keyID(key.getKeyID()).build(),
                claims.build());
        jwt.sign(new ECDSASigner(key));
        return jwt.serialize();
    }
}

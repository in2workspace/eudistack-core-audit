package com.eudistack.audit.infrastructure.persistence.repository;

import com.fasterxml.jackson.core.JsonProcessingException;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.eudistack.audit.domain.model.AuditEvent;
import com.eudistack.audit.domain.model.Result;
import com.eudistack.audit.domain.policy.CanonicalJson;
import org.springframework.jdbc.core.RowMapper;
import org.springframework.jdbc.core.simple.JdbcClient;

import java.sql.ResultSet;
import java.sql.SQLException;
import java.time.OffsetDateTime;
import java.time.ZoneOffset;
import java.util.UUID;

/**
 * SQL of {@code audit_event}, shared by every adapter. Unqualified: the schema is the transaction's
 * {@code search_path}.
 */
public final class EventSql {

    public static final String COLUMNS = "event_id, event_type, event_version, occurred_at, recorded_at, tenant, "
            + "organization, source, actor, action, resource, result, reason, correlation_id, details";

    private static final String INSERT = """
            INSERT INTO audit_event (event_id, event_type, event_version, occurred_at, tenant, organization, source,
                                     actor, action, resource, result, reason, correlation_id, details, payload_hash)
            VALUES (:event_id, :event_type, :event_version, :occurred_at, :tenant, :organization, :source,
                    CAST(:actor AS jsonb), :action, :resource, :result, :reason, :correlation_id,
                    CAST(:details AS jsonb), :payload_hash)
            ON CONFLICT (event_id) DO NOTHING
            """;

    private final ObjectMapper mapper;

    public EventSql(ObjectMapper mapper) {
        this.mapper = mapper;
    }

    /**
     * Inserts the event unless its {@code event_id} exists. {@code recorded_at} is set by the database
     * ({@code clock_timestamp()}).
     *
     * @return 1 when inserted, 0 when the {@code event_id} was already there
     */
    public int insertIfAbsent(JdbcClient jdbc, AuditEvent event, byte[] payloadHash) {
        return jdbc.sql(INSERT)
                .param("event_id", event.eventId())
                .param("event_type", event.eventType())
                .param("event_version", event.eventVersion())
                .param("occurred_at", OffsetDateTime.ofInstant(event.occurredAt(), ZoneOffset.UTC))
                .param("tenant", event.tenant())
                .param("organization", event.organization())
                .param("source", event.source())
                .param("actor", write(event.actor()))
                .param("action", event.action())
                .param("resource", event.resource())
                .param("result", event.result().wireValue())
                .param("reason", event.reason())
                .param("correlation_id", event.correlationId())
                .param("details", write(event.details()))
                .param("payload_hash", payloadHash)
                .update();
    }

    /**
     * Inserts an event generated by the API; its hash covers its own canonical JSON.
     */
    public int insertOwnEvent(JdbcClient jdbc, AuditEvent event) {
        return insertIfAbsent(jdbc, event, CanonicalJson.sha256(event.toJson()));
    }

    public RowMapper<AuditEvent> rowMapper() {
        return this::map;
    }

    private AuditEvent map(ResultSet rs, int row) throws SQLException {
        try {
            return new AuditEvent(
                    rs.getObject("event_id", UUID.class),
                    rs.getString("event_type"),
                    rs.getString("event_version"),
                    rs.getObject("occurred_at", OffsetDateTime.class).toInstant(),
                    rs.getObject("recorded_at", OffsetDateTime.class).toInstant(),
                    rs.getString("tenant"),
                    rs.getString("organization"),
                    rs.getString("source"),
                    mapper.readTree(rs.getString("actor")),
                    rs.getString("action"),
                    rs.getString("resource"),
                    Result.fromWire(rs.getString("result")).orElseThrow(),
                    rs.getString("reason"),
                    rs.getString("correlation_id"),
                    mapper.readTree(rs.getString("details")));
        } catch (JsonProcessingException e) {
            throw new SQLException("Stored JSON could not be read", e);
        }
    }

    private String write(Object node) {
        try {
            return mapper.writeValueAsString(node);
        } catch (JsonProcessingException e) {
            throw new IllegalStateException("Event JSON could not be written", e);
        }
    }
}
